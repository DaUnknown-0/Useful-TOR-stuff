/*
 * UnknownHat - the full-body costume "The Unknown" as a hat in TOR's wardrobe, exclusive to the mod's author.
 *
 * Registration: for EVERY player with this mod, so that the others see it when the author wears it. The route is
 * the one Unknown's Collection uses for its costume hats (UCHats.cs there, read it for the long reasoning): TOR
 * builds custom hats only from files in <Among Us>\TheOtherHats, so the three embedded PNGs (Resources\unknownhat,
 * generated by Assets\Branding\unknown\unknown_hat.py) are written there at start, and CustomHat records pointing
 * at them are appended by reflection to the internal CustomHatManager.UnregisteredHats. TOR then turns them into
 * real HatData on its normal path. A GenerateDownloadList postfix keeps TOR from asking its repository for files
 * it does not host (the records carry no hash, which TOR reads as "download me").
 * Layers: main = front view on the real crewmate silhouette (visor cut out), back = an almost empty image (the
 * short coat has no tails behind the player; the layer stays because the ladder and corpse poses are recognised by
 * the game switching it off), climb = rear view for the ladder. All images come from
 * Assets\Branding\unknown\gpt_outfit.py (GPT outfit, User 29.10.).
 *
 * Exclusive wardrobe entry: only the author sees and can equip it.
 *   - HatManager.GetUnlockedHats postfix drops the hat from the list for everybody else. TOR builds its whole
 *     hat tab from exactly that list (HatsTabPatches.OnEnablePrefix), so no chip, no package title and no gap in
 *     the grid appears. HatSearch (which runs on the finished tab) never sees it either.
 *   - HatsTab.ClickEquip prefix: a non-author cannot equip it by any input path (controller selects and equips
 *     separately).
 *   - PlayerControl.RpcSetHat prefix: if a non-author's local player is about to announce this hat (a hat id
 *     left in the save file, another mod's setLook), it announces no hat instead. A tick (HudManager.Update
 *     postfix, 1 s) and the wardrobe opening swap a saved copy of it back to the empty hat.
 *   The author is never touched: for him every one of these is a no-op.
 *
 * Who the author is: EasterEggCoding.IsOwner (SHA-256 of his PUID or friend code, the ids are not in the source).
 * The local player is checked through his PlayerControl when there is one; in the main menu there is none, so
 * the account's own ids come from the EOS manager. Purely cosmetic, nothing is sent that vanilla would not send.
 */

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using AmongUs.Data;
using HarmonyLib;
using Il2CppInterop.Runtime.InteropTypes.Arrays;
using TheOtherRoles.Modules.CustomHats;
using UnityEngine;

namespace UsefulTORStuff {
    public static class UnknownHat {
        private const string HatName = "The Unknown";
        private const string Author = "DaUnknown-0";
        private const string Package = "Unknown's Collective";
        private const string NoHatId = "hat_NoHat";   // vanilla "empty" hat

        // CreateHatBehaviour builds the product id as "hat_" + Name with spaces turned into underscores.
        private static readonly string HatId = "hat_" + HatName.Replace(' ', '_');

        private const string ResourcePrefix = "UsefulTORStuff.Resources.unknownhat.";
        // Disk names with a "UTS_" prefix so they can never collide with a file of the official hat repository.
        private const string MainFile = "UTS_Unknown.png", BackFile = "UTS_Unknown_back.png", ClimbFile = "UTS_Unknown_climb.png";
        private static readonly (string Res, string File)[] Files = {
            ("unknown_main.png", MainFile), ("unknown_back.png", BackFile), ("unknown_climb.png", ClimbFile),
        };
        private static readonly string[] OwnDiskFiles = { MainFile, BackFile, ClimbFile };

        private static bool registered;

        // ---- registration ------------------------------------------------------------------------

        public static void TryPatch(Harmony harmony) {
            try {
                string dir = ResolveHatsDirectory();
                if (dir == null) {
                    UsefulTORStuffPlugin.Logger?.LogWarning("[UnknownHat] could not resolve TOR's hats directory, hat skipped.");
                    return;
                }
                foreach (var (res, file) in Files)
                    if (!ExtractIfNeeded(dir, ResourcePrefix + res, file)) return;   // a missing file would make TOR retry forever

                var field = typeof(CustomHatManager).GetField("UnregisteredHats", BindingFlags.NonPublic | BindingFlags.Static);
                if (field?.GetValue(null) is not List<CustomHat> list) {
                    UsefulTORStuffPlugin.Logger?.LogWarning("[UnknownHat] CustomHatManager.UnregisteredHats not found, hat skipped.");
                    return;
                }
                if (list.Any(h => h?.Name == HatName)) {
                    UsefulTORStuffPlugin.Logger?.LogWarning($"[UnknownHat] a hat named '{HatName}' is already registered, ours is skipped.");
                    return;
                }
                list.Add(new CustomHat {
                    Name = HatName, Author = Author, Package = Package,
                    Resource = MainFile, BackResource = BackFile, ClimbResource = ClimbFile,
                    Adaptive = false, Bounce = false, Behind = true,   // BackResource forces Behind anyway
                });
                registered = true;

                var target = AccessTools.Method(typeof(CustomHatManager), "GenerateDownloadList");
                if (target != null)
                    harmony.Patch(target, postfix: new HarmonyMethod(AccessTools.Method(typeof(UnknownHat), nameof(StripOwnFiles))));
                else
                    UsefulTORStuffPlugin.Logger?.LogWarning("[UnknownHat] GenerateDownloadList not found, TOR may log 404s for the hat files.");
                UsefulTORStuffPlugin.Logger?.LogInfo($"[UnknownHat] registered '{HatName}' in {dir}.");
            } catch (Exception ex) {
                UsefulTORStuffPlugin.Logger?.LogError($"[UnknownHat] setup failed: {ex}");
            }
        }

        // CustomHatManager.HatsDirectory is internal; the fallback rebuilds it from the public directory name.
        private static string ResolveHatsDirectory() {
            try {
                var prop = typeof(CustomHatManager).GetProperty("HatsDirectory", BindingFlags.NonPublic | BindingFlags.Static);
                if (prop?.GetValue(null) is string fromTor && !string.IsNullOrEmpty(fromTor)) return fromTor;
            } catch { }
            try {
                string root = Path.GetDirectoryName(Application.dataPath);
                return string.IsNullOrEmpty(root) ? null : Path.Combine(root, CustomHatManager.ResourcesDirectory);
            } catch { return null; }
        }

        // Writes the embedded PNG into TheOtherHats, only when missing or different (a normal start does one read).
        private static bool ExtractIfNeeded(string dir, string resourceName, string fileName) {
            try {
                byte[] data;
                using (var stream = typeof(UnknownHat).Assembly.GetManifestResourceStream(resourceName)) {
                    if (stream == null) {
                        UsefulTORStuffPlugin.Logger?.LogWarning($"[UnknownHat] embedded resource missing: {resourceName}");
                        return false;
                    }
                    data = new byte[stream.Length];
                    int read = 0;
                    while (read < data.Length) {
                        int n = stream.Read(data, read, data.Length - read);
                        if (n <= 0) break;
                        read += n;
                    }
                    if (read != data.Length) return false;
                }
                if (!Directory.Exists(dir)) Directory.CreateDirectory(dir);
                string path = Path.Combine(dir, fileName);
                if (File.Exists(path)) {
                    var existing = File.ReadAllBytes(path);
                    if (existing.Length == data.Length && existing.SequenceEqual(data)) return true;
                }
                File.WriteAllBytes(path, data);
                UsefulTORStuffPlugin.Logger?.LogInfo($"[UnknownHat] wrote {fileName}.");
                return true;
            } catch (Exception ex) {
                UsefulTORStuffPlugin.Logger?.LogError($"[UnknownHat] could not extract {fileName}: {ex.Message}");
                return false;
            }
        }

        // The returned list is the object HatsLoader iterates, so removing in place is enough.
        private static void StripOwnFiles(List<string> __result) {
            try { __result?.RemoveAll(f => OwnDiskFiles.Contains(f)); }
            catch (Exception ex) { UsefulTORStuffPlugin.Logger?.LogWarning($"[UnknownHat] download strip failed: {ex.Message}"); }
        }

        // ---- who may wear it ---------------------------------------------------------------------

        private static bool authorKnown;
        private static bool authorCached;
        private static float authorCheckedAt = -100f;

        /// <summary>True when the account behind this game is the author's. Cached for a few seconds (SHA-256 per call).</summary>
        internal static bool LocalIsAuthor() {
            if (authorKnown) return true;
            float now = Time.realtimeSinceStartup;
            if (now - authorCheckedAt < 3f) return authorCached;
            authorCheckedAt = now;
            bool result = false;
            try {
                var lp = PlayerControl.LocalPlayer;
                if (lp != null && lp.Data != null && (!string.IsNullOrEmpty(lp.Data.Puid) || !string.IsNullOrEmpty(lp.Data.FriendCode)))
                    result = EasterEggCoding.IsOwner(lp);
                else {
                    // main menu: no PlayerControl, ask the account directly
                    var eos = EOSManager.Instance;
                    if (eos != null) result = EasterEggCoding.IsOwnerId(eos.ProductUserId?.ToString(), eos.FriendCode);
                }
            } catch { }
            authorCached = result;
            if (result) authorKnown = true;
            return result;
        }

        private static bool IsOurs(string productId) => productId == HatId;

        // ---- exclusive wardrobe entry --------------------------------------------------------------

        // TOR's hat tab is built from this list; no entry here means no chip and no gap.
        [HarmonyPatch(typeof(HatManager), nameof(HatManager.GetUnlockedHats))]
        private static class UnlockedHatsPatch {
            public static void Postfix(ref Il2CppReferenceArray<HatData> __result) {
                try {
                    if (!registered || __result == null || LocalIsAuthor()) return;
                    int ours = 0;
                    foreach (var h in __result) if (h != null && IsOurs(h.ProductId)) ours++;
                    if (ours == 0) return;
                    var kept = new List<HatData>(__result.Length);
                    foreach (var h in __result) if (h != null && !IsOurs(h.ProductId)) kept.Add(h);
                    __result = new Il2CppReferenceArray<HatData>(kept.ToArray());
                } catch (Exception ex) {
                    UsefulTORStuffPlugin.Logger?.LogWarning($"[UnknownHat] wardrobe filter failed: {ex.Message}");
                }
            }
        }

        // Backstop: the controller flow selects with one button and equips with another.
        [HarmonyPatch(typeof(HatsTab), nameof(HatsTab.ClickEquip))]
        private static class EquipPatch {
            public static bool Prefix(HatsTab __instance) {
                try {
                    var hat = __instance != null ? __instance.currentHat : null;
                    if (hat != null && IsOurs(hat.ProductId) && !LocalIsAuthor()) return false;
                } catch { }
                return true;
            }
        }

        // A hat id that survives in the save (or comes from another mod's setLook) must not be announced by a non-author.
        [HarmonyPatch(typeof(PlayerControl), nameof(PlayerControl.RpcSetHat))]
        private static class RpcSetHatPatch {
            public static void Prefix(PlayerControl __instance, ref string hatId) {
                try {
                    if (!IsOurs(hatId) || __instance != PlayerControl.LocalPlayer || LocalIsAuthor()) return;
                    hatId = NoHatId;
                    UsefulTORStuffPlugin.Logger?.LogInfo("[UnknownHat] not the author: announcing no hat instead.");
                } catch { }
            }
        }

        [HarmonyPatch(typeof(HatsTab), nameof(HatsTab.OnEnable))]
        private static class TabOpenPatch {
            public static void Postfix() => SanitizeSavedHat();
        }

        private static float nextSanitize;

        [HarmonyPatch(typeof(HudManager), nameof(HudManager.Update))]
        private static class TickPatch {
            public static void Postfix() {
                if (!registered || Time.time < nextSanitize) return;
                nextSanitize = Time.time + 1f;
                SanitizeSavedHat();
            }
        }

        // ---- walk loop -----------------------------------------------------------------------------
        // TOR hats have one front image. While the wearer runs, the front layer gets one of 12 walk frames
        // (Resources\unknownhat\unknown_walk_N.png, Assets\Branding\unknown\gpt_overlay.py), picked from the
        // crewmate's own run animation so the outfit bobs with the real body. Standing, the ladder and the corpse pose keep TOR's images: the ladder and corpse
        // poses switch the back layer off and put their own image on the front layer, so nothing is written then.

        private const int WalkFrames = 12;
        private static Sprite[] walkFrames;
        private static Sprite walkFor;          // the main sprite the walk frames were sized against
        private static Sprite idleSprite;       // TOR's main sprite of the hat, put back when the wearer stops
        private static bool walkFailed;

        [HarmonyPatch(typeof(HatParent), nameof(HatParent.LateUpdate))]
        private static class WalkPatch {
            public static void Postfix(HatParent __instance) {
                if (!registered || walkFailed || __instance == null) return;
                try { Animate(__instance); }
                catch (Exception ex) {
                    walkFailed = true;
                    UsefulTORStuffPlugin.Logger?.LogWarning($"[UnknownHat] walk loop disabled after an error: {ex.Message}");
                }
            }
        }

        private static void Animate(HatParent hp) {
            var hat = hp.Hat;
            if (hat == null || !IsOurs(hat.ProductId)) return;
            var front = hp.FrontLayer;
            var back = hp.BackLayer;
            if (front == null || !front.enabled || front.sprite == null) return;
            if (back == null || !back.enabled) return;
            FollowHead(hp, front, back);

            var current = front.sprite;
            if (walkFrames == null || Array.IndexOf(walkFrames, current) < 0) idleSprite = current;
            if (idleSprite == null) return;

            float cycle = -1f;
            var pc = hp.GetComponentInParent<PlayerControl>();
            if (pc != null && pc.Data != null && !pc.Data.IsDead && !pc.onLadder && !pc.inVent && !pc.inMovingPlat) {
                var anims = pc.MyPhysics != null ? pc.MyPhysics.Animations : null;
                if (anims != null && anims.IsPlayingRunAnimation()) {
                    var animator = anims.Animator != null ? anims.Animator.m_animator : null;
                    if (animator != null) {
                        float t = animator.GetCurrentAnimatorStateInfo(0).normalizedTime;
                        cycle = t - Mathf.Floor(t);
                    }
                }
            }

            Sprite want = idleSprite;
            if (cycle >= 0f && EnsureWalkFrames(idleSprite)) {
                var f = walkFrames[Mathf.Clamp(Mathf.FloorToInt(cycle * WalkFrames), 0, WalkFrames - 1)];
                if (f != null) want = f;
            }
            if (front.sprite != want) front.sprite = want;
        }

        // The walk frames are measured against a hat that hangs on the head node (NodeId 0), like the costume hats of
        // Unknown's Collection (UCHats.SetBounceNode): the front layer bobs with the head and the
        // frames only add what the body does relative to it. TOR leaves a non-bouncing custom hat on another node, so the
        // costume moved twice and cut into the visor (User 29.10.). Same fix as UCHats: sync on the head, back layer copies
        // the front layer's X/Y (the sync only moves the front layer).
        private static void FollowHead(HatParent hp, SpriteRenderer front, SpriteRenderer back) {
            var sync = hp.SpriteSyncNode != null ? hp.SpriteSyncNode : hp.GetComponent<PowerTools.SpriteAnimNodeSync>();
            if (sync != null && sync.NodeId != 0) sync.NodeId = 0;
            var f = front.transform.localPosition;
            var b = back.transform.localPosition;
            if (Mathf.Abs(b.x - f.x) > 0.0005f || Mathf.Abs(b.y - f.y) > 0.0005f)
                back.transform.localPosition = new Vector3(f.x, f.y, b.z);
        }

        // The frames share the main image's canvas, so pivot and scale are taken from TOR's main sprite.
        private static bool EnsureWalkFrames(Sprite main) {
            if (walkFrames != null && walkFor == main) return true;
            var frames = new Sprite[WalkFrames];
            Vector2 pivot = new Vector2(main.pivot.x / main.rect.width, main.pivot.y / main.rect.height);
            for (int i = 0; i < WalkFrames; i++) {
                byte[] data = ReadResource(ResourcePrefix + "unknown_walk_" + (i + 1) + ".png");
                if (data == null) { walkFailed = true; UsefulTORStuffPlugin.Logger?.LogWarning("[UnknownHat] walk frame " + (i + 1) + " missing."); return false; }
                var tex = new Texture2D(2, 2, TextureFormat.ARGB32, false);
                if (!ImageConversion.LoadImage(tex, data, false)) { walkFailed = true; return false; }
                tex.Apply(false, true);
                tex.hideFlags |= HideFlags.HideAndDontSave | HideFlags.DontSaveInEditor;
                float ppu = main.pixelsPerUnit * tex.width / main.rect.width;
                var s = Sprite.Create(tex, new Rect(0, 0, tex.width, tex.height), pivot, ppu);
                s.hideFlags |= HideFlags.HideAndDontSave | HideFlags.DontSaveInEditor;
                frames[i] = s;
            }
            walkFrames = frames;
            walkFor = main;
            return true;
        }

        private static byte[] ReadResource(string name) {
            using var stream = typeof(UnknownHat).Assembly.GetManifestResourceStream(name);
            if (stream == null) return null;
            var data = new byte[stream.Length];
            int read = 0;
            while (read < data.Length) {
                int n = stream.Read(data, read, data.Length - read);
                if (n <= 0) break;
                read += n;
            }
            return read == data.Length ? data : null;
        }

        // Saved hat is ours but the account is not the author's: back to the empty hat, and tell the lobby when in one.
        private static void SanitizeSavedHat() {
            try {
                if (!registered) return;
                var customization = DataManager.Player?.Customization;
                if (customization == null || !IsOurs(customization.Hat) || LocalIsAuthor()) return;
                customization.Hat = NoHatId;
                var lp = PlayerControl.LocalPlayer;
                if (lp != null && lp.Data != null && IsOurs(lp.Data.DefaultOutfit.HatId)) lp.RpcSetHat(NoHatId);
                UsefulTORStuffPlugin.Logger?.LogInfo("[UnknownHat] saved hat reset (not the author).");
            } catch (Exception ex) {
                UsefulTORStuffPlugin.Logger?.LogWarning($"[UnknownHat] sanitize failed: {ex.Message}");
            }
        }
    }
